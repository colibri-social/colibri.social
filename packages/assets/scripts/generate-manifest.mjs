// Generates src/login-manifest.ts from the SVGs in files/login/.
// The client renders these by root URL (e.g. /login/colibri.svg), which the
// host serves from this package's files/ dir via the static-copy provisioning.
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(
	fileURLToPath(new URL("../package.json", import.meta.url)),
);
const loginDir = join(root, "files", "login");

const logos = readdirSync(loginDir)
	.filter((name) => name.endsWith(".svg"))
	.sort();

const urls = logos.map((name) => `/login/${name}`);

const out = `// AUTO-GENERATED by scripts/generate-manifest.mjs — do not edit.
export const loginLogos = ${JSON.stringify(urls, null, "\t")} as const;
`;

writeFileSync(join(root, "src", "login-manifest.ts"), out);
console.log(`Wrote login-manifest.ts with ${urls.length} logos.`);
