const VARIATION_SELECTOR = "️";

const withoutVariation = (emoji: string) =>
	emoji.replaceAll(VARIATION_SELECTOR, "");

const RANK_BY_EMOJI = new Map<string, number>(
	EMOJI_FREQUENCY.map((emoji, rank) => [withoutVariation(emoji), rank]),
);

export const UNRANKED_EMOJI = EMOJI_FREQUENCY.length;

export const emojiFrequencyRank = (emoji: string): number =>
	RANK_BY_EMOJI.get(withoutVariation(emoji)) ?? UNRANKED_EMOJI;
